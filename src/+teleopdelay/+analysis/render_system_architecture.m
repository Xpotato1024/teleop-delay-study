function entry = render_system_architecture(figuresDirectory, config)
% render_system_architecture  Draw the fixed model-contract system diagram.

contract = teleopdelay.analysis.architecture_contract();
textContract = teleopdelay.analysis.figure_text_contract();
fig = figure("Visible", "off", "Color", "white", "Position", [100, 100, 1500, 850]);
cleanup = onCleanup(@() teleopdelay.analysis.close_figure(fig));
axes(fig, "Visible", "off", "Position", [0, 0, 1, 1]);
positions = node_positions();
colors = node_colors();
annotation(fig, "textbox", [0.03, 0.92, 0.94, 0.05], ...
    "String", textContract.figure_01.title, "EdgeColor", "none", ...
    "HorizontalAlignment", "center", "FontSize", 18, "Interpreter", "none");
for index = 1:numel(contract.nodes)
    node = char(contract.nodes(index));
    annotation(fig, "textbox", positions.(node), ...
        "String", contract.labels(index), "FitBoxToText", "off", ...
        "HorizontalAlignment", "center", "VerticalAlignment", "middle", ...
        "FontSize", 11, "BackgroundColor", colors.(node), ...
        "Color", [0.05, 0.05, 0.05], "Interpreter", "none");
end
for index = 1:size(contract.required_edges, 1)
    source = char(contract.required_edges(index, 1));
    target = char(contract.required_edges(index, 2));
    [sourcePoint, targetPoint] = boundary_points(positions.(source), positions.(target));
    annotation(fig, "arrow", [sourcePoint(1), targetPoint(1)], ...
        [sourcePoint(2), targetPoint(2)], "LineWidth", 1.5, ...
        "Color", [0.15, 0.15, 0.15]);
end
annotation(fig, "textbox", [0.30, 0.06, 0.40, 0.05], ...
    "String", contract.plant_model + "。" + contract.evaluation_note + "。", ...
    "EdgeColor", "none", "HorizontalAlignment", "center", ...
    "FontSize", 11, "Interpreter", "none");
fontName = teleopdelay.analysis.style_figure(fig);
metadata = struct( ...
    "trajectory", "all", "case_ids", "", "caption", textContract.figure_01.caption, ...
    "metric", textContract.figure_01.metric, "axes_contract", textContract.figure_01.axes_contract, ...
    "font_name", fontName);
entry = teleopdelay.analysis.save_figure(fig, figuresDirectory, ...
    "figure_01_system_architecture", metadata, config.figure_dpi);
teleopdelay.analysis.close_figure(fig);
clear cleanup;
end

