function [sourcePoint, targetPoint] = boundary_points(source, target)
sourceCenter = [source(1) + source(3) / 2, source(2) + source(4) / 2];
targetCenter = [target(1) + target(3) / 2, target(2) + target(4) / 2];
direction = targetCenter - sourceCenter;
sourcePoint = sourceCenter + rectangle_intersection(source, direction);
targetPoint = targetCenter - rectangle_intersection(target, direction);
end

function offset = rectangle_intersection(rectangle, direction)
if all(direction == 0)
    error("teleopDelay:AnalysisArchitectureGeometryInvalid", ...
        "Architecture edge endpoints cannot share a node center.");
end
halfWidth = rectangle(3) / 2;
halfHeight = rectangle(4) / 2;
scales = [halfWidth / abs(direction(1)), halfHeight / abs(direction(2))];
scales(~isfinite(scales)) = inf;
offset = direction * min(scales);
end
