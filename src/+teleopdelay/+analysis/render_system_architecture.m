function entry = render_system_architecture(figuresDirectory, config)
% render_system_architecture  Draw the fixed analysis-facing system diagram.

fig = figure("Visible", "off", "Color", "white", "Position", [100, 100, 1500, 800]);
cleanup = onCleanup(@() close(fig));
axis off;
annotation(fig, "textbox", [0.02, 0.87, 0.18, 0.08], "String", "continuous reference", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.86, 0.92, 1], "FitBoxToText", "off");
annotation(fig, "textbox", [0.25, 0.87, 0.18, 0.08], "String", "sampled communication", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.90, 0.96, 0.90], "FitBoxToText", "off");
annotation(fig, "textbox", [0.48, 0.87, 0.18, 0.08], "String", "ZOH / CV reconstruction", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [1.00, 0.94, 0.82], "FitBoxToText", "off");
annotation(fig, "textbox", [0.75, 0.87, 0.18, 0.08], "String", "reference plant", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.92, 0.88, 1], "FitBoxToText", "off");
annotation(fig, "textbox", [0.75, 0.54, 0.18, 0.08], "String", "ZOH plant", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [1.00, 0.90, 0.90], "FitBoxToText", "off");
annotation(fig, "textbox", [0.75, 0.22, 0.18, 0.08], "String", "CV plant", ...
    "HorizontalAlignment", "center", "FontSize", 13, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.90, 0.94, 1], "FitBoxToText", "off");
annotation(fig, "textbox", [0.25, 0.52, 0.18, 0.10], "String", sprintf('packet timestamp\nposition + velocity\nvalid / packet age'), ...
    "HorizontalAlignment", "center", "FontSize", 11, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.95, 0.95, 0.95], "FitBoxToText", "off");
annotation(fig, "textbox", [0.94, 0.52, 0.05, 0.20], "String", sprintf('evaluation\nvs reference'), ...
    "HorizontalAlignment", "center", "FontSize", 11, "Color", [0.05, 0.05, 0.05], "BackgroundColor", [0.95, 0.95, 0.95], "FitBoxToText", "off");
arrows = [ ...
    0.20 0.91 0.05 0; 0.43 0.91 0.05 0; 0.66 0.91 0.09 0; ...
    0.66 0.90 0.09 -0.27; 0.66 0.88 0.09 -0.59; 0.93 0.58 0.03 0; ...
    0.93 0.26 0.03 0; 0.93 0.90 0.03 -0.28];
for index = 1:size(arrows, 1)
    annotation(fig, "arrow", [arrows(index, 1), arrows(index, 1) + arrows(index, 3)], ...
        [arrows(index, 2), arrows(index, 2) + arrows(index, 4)], "LineWidth", 1.5);
end
annotation(fig, "textbox", [0.20, 0.06, 0.60, 0.08], "String", ...
    "Signal flow is rendered from the fixed model contract; no Simulink screenshot is used.", ...
    "HorizontalAlignment", "center", "FontSize", 11, "Color", [0.05, 0.05, 0.05], "EdgeColor", "none");
teleopdelay.analysis.style_figure(fig);
entry = teleopdelay.analysis.save_figure(fig, figuresDirectory, ...
    "figure_01_system_architecture", struct( ...
    "trajectory", "all", "case_ids", "", "caption", ...
    "Continuous reference, sampled communication, ZOH/CV reconstruction, three plants, and evaluation against reference.", ...
    "metric", "signal architecture", "axes_contract", "fixed layout; no data axes"), config.figure_dpi);
clear cleanup;
end
