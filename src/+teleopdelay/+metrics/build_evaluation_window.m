function evaluation = build_evaluation_window(config, trajectory, simulation)
% build_evaluation_window  nominal境界と実sample境界から評価windowを構築する。

teleopdelay.config.validate_config(config);
validate_time_vector(trajectory, "trajectory.time_s");
validate_time_vector(simulation, "simulation.time_s");

time_s = simulation.time_s;
period_s = 2 * pi / config.trajectory.omega;
nominal_start_s = config.evaluation.warmup_cycles * period_s;
nominal_end_s = config.evaluation.total_cycles * period_s;
grid_tolerance = 16 * eps(max([1; abs(time_s); abs(nominal_start_s); abs(nominal_end_s)]));
if time_s(1) > nominal_start_s + grid_tolerance || ...
        time_s(end) < nominal_end_s - grid_tolerance
    error("teleopDelay:EvaluationWindowOutOfRange", ...
        "The simulation time vector does not cover the nominal evaluation window.");
end

mask = time_s >= nominal_start_s - grid_tolerance & ...
    time_s <= nominal_end_s + grid_tolerance;
mask = logical(mask(:));
sample_indices = find(mask);
if isempty(sample_indices)
    error("teleopDelay:EmptyEvaluationWindow", ...
        "The nominal evaluation window contains no simulation samples.");
end

evaluation = struct( ...
    "period_s", period_s, ...
    "total_cycles", config.evaluation.total_cycles, ...
    "warmup_cycles", config.evaluation.warmup_cycles, ...
    "nominal_start_s", nominal_start_s, ...
    "nominal_end_s", nominal_end_s, ...
    "sample_start_s", time_s(sample_indices(1)), ...
    "sample_end_s", time_s(sample_indices(end)), ...
    "sample_count", double(numel(sample_indices)), ...
    "mask", mask);
end

function validate_time_vector(container, fieldName)
field = char(extractAfter(fieldName, "."));
if ~isstruct(container) || ~isfield(container, field)
    error("teleopDelay:InvalidEvaluationInput", ...
        "%s is required.", fieldName);
end
time_s = container.(field);
if ~(isa(time_s, "double") && iscolumn(time_s) && isreal(time_s) && ...
        all(isfinite(time_s)) && ~isempty(time_s) && all(diff(time_s) > 0))
    error("teleopDelay:InvalidEvaluationInput", ...
        "%s must be a finite, strictly increasing N-by-1 double vector.", fieldName);
end
end
